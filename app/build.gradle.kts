val appVersion = "1.0.0"
val appVersionCode = 1

// Release signing: the keystore comes from the repository secrets in CI (see README).
// Without them the release APK is signed with the debug key kept in keystore/debug.keystore,
// so updates install over each other until the real key is set up.
val releaseKeystore: String? = System.getenv("ARTCORE_KEYSTORE")?.takeIf { it.isNotBlank() && file(it).exists() }

android {
    namespace = "com.ruf790.artcore.remote"
    compileSdk = 37

    defaultConfig {
        applicationId = "com.ruf790.artcore.remote"
        minSdk = 26
        targetSdk = 37
        versionCode = appVersionCode
        versionName = appVersion
        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
    }

    signingConfigs {
        getByName("debug") {
            storeFile = rootProject.file("keystore/debug.keystore")
            storePassword = "android"
            keyAlias = "androiddebugkey"
            keyPassword = "android"
        }
        if (releaseKeystore != null) {
            create("release") {
                storeFile = file(releaseKeystore)
                storePassword = System.getenv("ARTCORE_KEYSTORE_PASSWORD")
                keyAlias = System.getenv("ARTCORE_KEY_ALIAS")
                keyPassword = System.getenv("ARTCORE_KEY_PASSWORD")
            }
        }
    }

    buildTypes {
        getByName("release") {
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
            signingConfig = signingConfigs.getByName(if (releaseKeystore != null) "release" else "debug")
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    buildFeatures {
        compose = true
    }

    lint {
        abortOnError = false
        checkReleaseBuilds = false
    }

    testOptions {
        unitTests.isReturnDefaultValues = true
    }
}

